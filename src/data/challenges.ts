export function getChallenge(id: string) {
  return challenges.find((c) => c.id === id);
}

export function getChallengesByCourse(course: string) {
  return challenges.filter((c) => c.course === course);
}

export function getNextChallenge(currentId: string) {
  const idx = challenges.findIndex((c) => c.id === currentId);
  if (idx === -1 || idx === challenges.length - 1) return null;
  // Prefer same course
  const current = challenges[idx];
  const sameCourse = challenges.slice(idx + 1).find((c) => c.course === current.course);
  return sameCourse || challenges[idx + 1];
}
